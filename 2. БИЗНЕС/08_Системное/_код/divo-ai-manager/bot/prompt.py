def _read(rel: str) -> str:
    path: Path = settings.workspace / rel
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8").strip()


def stock_status() -> str:
    """Одна строка для /stock и логов."""
    index = _read("KB/сток/_ИНДЕКС.md")
    if not index:
        return "сток не выгружен"
    for line in index.splitlines():
        if line.startswith("> Обновлено"):
            return line.lstrip("> ").strip()
    return "сток выгружен, метка времени не найдена"


def build() -> str:
    blocks = []
    stock_loaded = False
    for rel in PARTS:
        text = _read(rel)
        if not text:
            continue
        stock_loaded = stock_loaded or rel.startswith("KB/сток")
        blocks.append(text)
    if not stock_loaded:
        blocks.append(
            "# Сток\n\nВыгрузка стока недоступна. Наличие конкретных машин не "
            "подтверждай и не отрицай: «уточню по наличию» плюс передача человеку."
        )
    blocks.append(
        CHANNEL_RULES % {
            "mark": HANDOFF_MARK,
            "silence": SILENCE_MARK,
            "media_photo": MEDIA_PHOTO_MARK,
            "media_video": MEDIA_VIDEO_MARK,
            "reveal": REVEAL_ON if settings.reveal_bot else REVEAL_OFF,
        }
    )
    return "\n\n---\n\n".join(blocks).strip()
