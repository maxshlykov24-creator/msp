# Доп. оверрайды по хвосту имени (если basename.lower() endswith)
SUFFIX_OVERRIDES: list[tuple[str, str]] = []


def norm(s: str) -> str:
    return unicodedata.normalize("NFC", s).lower()


def classify(name: str) -> str:
    b = Path(name).name
    key = norm(b)
    if key in OVERRIDES:
        return OVERRIDES[key]
    # точное имя с автором — только полное key
    for folder, subs in RULES:
        for sub in subs:
            if sub in key:
                return folder
    return "Прочее"


def main() -> None:
    for sub in SUBDIRS:
        (DST / sub).mkdir(parents=True, exist_ok=True)
    moved = 0
    for p in sorted(SRC.iterdir()):
        if p.suffix.lower() != ".md":
            continue
        theme = classify(p.name)
        dest_dir = DST / THEME_TO_SUBDIR[theme]
        dest = dest_dir / p.name
        if dest.exists():
            raise SystemExit(f"целевой файл уже есть: {dest}")
        shutil.move(str(p), str(dest))
        moved += 1
    print(f"перенесено {moved} файлов в {DST}")


if __name__ == "__main__":
    main()
