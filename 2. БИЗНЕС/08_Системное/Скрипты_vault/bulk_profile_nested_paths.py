    for i, nm in [(4, "Идеи поездок"), (3, "Впечатления"), (2, "Визы"), (1, "Билеты")]:
        a(f"3.06. Путешествия/{i}. {nm}", f"3.6. Путешествия/3.6.{i}. {nm}")

