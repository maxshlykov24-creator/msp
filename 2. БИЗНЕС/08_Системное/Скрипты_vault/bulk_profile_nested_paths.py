    a("2. Дух/1. Изучение/3. Спасение", "2. Дух/2.1. Изучение/2.1.3. Спасение")
    a("2. Дух/1. Изучение", "2. Дух/2.1. Изучение")
    a("2. Дух/2. Проповеди", "2. Дух/2.2. Проповеди")
    a("2. Дух/3. Служение/1. Мое слово", "2. Дух/2.3. Служение/2.3.1. Мое слово")
    a("2. Дух/3. Служение/2. Церковь", "2. Дух/2.3. Служение/2.3.2. Церковь")
    a("2. Дух/3. Служение", "2. Дух/2.3. Служение")

